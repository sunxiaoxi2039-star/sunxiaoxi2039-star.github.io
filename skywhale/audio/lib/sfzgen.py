"""Generate calibrated wrapper SFZ files around the VSCO 2 CE instruments.

The VSCO 2 CE SFZ files map every sample with lokey/hikey/keycenter and
velocity ranges but their per-sample levels vary a lot (neighbouring notes
of the horn differ by up to 12 dB) and they expose no CC dynamics.  For
each instrument used by the score we therefore write a wrapper SFZ that

  * keeps VSCO's own sample mapping (same samples, keys, round robins),
  * adds a per-region `volume` so all samples of one dynamic layer sound
    equally loud (K-weighted RMS of the steady part of each sample),
  * stacks dynamic layers on a slope so louder layers really are louder,
  * for sustained articulations replaces velocity switching by an
    equal-power CC1 crossfade between the recorded dynamic layers (real
    timbral crescendo with the real samples, like modern libraries do),
  * adds CC11 expression (amplitude_oncc11) for hairpins.

Plucked/struck articulations keep velocity switching (with calibrated
levels).  The Salamander piano is used unmodified (it already has 16
well-matched velocity layers).
"""
import hashlib
import json
import os
import re

import numpy as np
import soundfile as sf
from scipy.signal import lfilter

# --------------------------------------------------------------------------
# minimal SFZ parser for the (simple) VSCO files


def parse_sfz(path):
    """Returns list of (header, [(opcode, value), ...]) in file order."""
    txt = open(path, encoding="latin-1").read().replace("\r", "")
    txt = re.sub(r"//[^\n]*", "", txt)
    items = []
    cur = None
    for line in txt.split("\n"):
        line = line.strip()
        if not line:
            continue
        # split headers from opcodes on the same line
        for tok in re.split(r"(<[a-z]+>)", line):
            tok = tok.strip()
            if not tok:
                continue
            if tok.startswith("<"):
                cur = (tok[1:-1], [])
                items.append(cur)
                continue
            for op in re.split(r"\s+(?=[A-Za-z0-9_]+=)", tok):
                if "=" in op and cur is not None:
                    k, v = op.split("=", 1)
                    cur[1].append((k.strip(), v.strip()))
    return items


def k_weight(x, sr):
    """ITU-R BS.1770 K-weighting (pre-filter + RLB), same as pyloudnorm."""
    import pyloudnorm as pyln
    meter = pyln.Meter(sr)
    y = x
    for _, f in meter._filters.items():
        y = lfilter(f.b, f.a, y)
    return y


def measure_sample(path, mode):
    x, sr = sf.read(path, always_2d=True)
    m = x.mean(axis=1)
    y = k_weight(m, sr)
    pk = np.abs(m).max() + 1e-12
    on = int(np.argmax(np.abs(m) > pk * 0.01))
    w = int(0.25 * sr)
    if mode == "sustain":
        a = on + int(0.5 * sr)
        b = min(len(y) - w, on + int(4.0 * sr), int(0.7 * len(y)))
        if b <= a:
            a, b = on, max(on + 1, len(y) - w)
        vals = [np.sqrt(np.mean(y[i:i + w] ** 2)) for i in range(a, b, w // 2)]
        lvl = np.median(vals) if vals else np.sqrt(np.mean(y ** 2))
    else:  # percussive: loudest 50 ms window in the first 0.6 s
        w = int(0.05 * sr)
        seg = y[on:on + int(0.6 * sr)]
        vals = [np.sqrt(np.mean(seg[i:i + w] ** 2)) for i in range(0, max(1, len(seg) - w), w // 4)]
        lvl = max(vals)
    return float(20 * np.log10(lvl + 1e-12)), float(len(m) / sr)


# --------------------------------------------------------------------------


def _get(ops, key, default=None):
    for k, v in ops:
        if k == key:
            return v
    return default


def build_wrapper(src_sfz, out_sfz, mode, cache, ref_db=-20.0, layer_span_db=14.0,
                  xfade_width=24, amp_veltrack=None, dyn_span_db=20.0, extra_global=None, release=None,
                  attack=None):
    """mode: 'sustain' (CC1 layer crossfade) or 'perc' (velocity layers).
    Returns a dict describing the calibration (for the docs/log)."""
    items = parse_sfz(src_sfz)
    base_dir = os.path.dirname(os.path.abspath(src_sfz))
    default_path = ""
    report = []
    out = []
    out.append(f"// generated by skywhale/audio/lib/sfzgen.py from {os.path.basename(src_sfz)} (VSCO 2 CE)")
    out.append(f"// mode={mode}: calibrated per-sample volume, "
               + ("CC1 dynamic-layer crossfade, " if mode == "sustain" else "velocity layers, ")
               + "CC11 expression")
    # first pass: collect regions with their resolved sample path
    regions = []
    for hdr, ops in items:
        if hdr == "control":
            dp = _get(ops, "default_path")
            if dp is not None:
                default_path = dp.replace("\\", "/")
        if hdr == "region":
            smp = _get(ops, "sample").replace("\\", "/")
            regions.append((os.path.join(base_dir, default_path, smp), ops))
    # measure
    for p, ops in regions:
        if p not in cache:
            cache[p] = measure_sample(p, mode)
    # velocity centres -> target level
    def target(lovel, hivel):
        if mode == "sustain":
            # loudness is driven continuously by CC1 (curve 7 below); every
            # recorded layer is normalised to the same level so the CC1
            # crossfade only changes timbre
            return ref_db
        c = 0.5 * (lovel + hivel)
        return ref_db - layer_span_db * (1.0 - c / 127.0)

    out.append("<control>")
    out.append("default_path=" + os.path.join(base_dir, default_path).replace("\\", "/").rstrip("/") + "/")
    out.append("hint_ram_based=1")  # load whole samples: no disk streaming / GC races in sfizz_render
    out.append("set_cc1=64")
    out.append("set_cc11=127")
    if mode == "sustain":
        # dB-linear dynamics curve for CC1: cc 0 -> -dyn_span_db, cc 127 -> 0 dB
        pts = " ".join(f"v{c:03d}={10 ** (dyn_span_db * (c / 127.0 - 1.0) / 20.0):.5f}"
                       for c in range(0, 128, 8)) + f" v127=1.00000"
        out.append("<curve>")
        out.append("curve_index=7 " + pts)
    out.append("<global>")
    glob_ops = []
    for hdr, ops in items:
        if hdr == "global":
            glob_ops = list(ops)
    for k, v in glob_ops:
        if k in ("volume",):
            continue
        if k == "ampeg_release" and release is not None:
            v = str(release)
        if k == "ampeg_attack" and attack is not None:
            v = str(attack)
        out.append(f"{k}={v}")
    if release is not None and not any(k == "ampeg_release" for k, _ in glob_ops):
        out.append(f"ampeg_release={release}")
    out.append("amplitude_oncc11=100")
    if mode == "sustain":
        out.append("xf_cccurve=power")
        out.append("amp_veltrack=0")
        out.append("amplitude_oncc1=100")
        out.append("amplitude_curvecc1=7")
    else:
        out.append(f"amp_veltrack={amp_veltrack if amp_veltrack is not None else 50}")
    for line in (extra_global or []):
        out.append(line)
    for hdr, ops in items:
        if hdr in ("control", "global"):
            continue
        out.append(f"<{hdr}>")
        if hdr != "region":
            for k, v in ops:
                if k == "volume":
                    continue
                out.append(f"{k}={v}")
            continue
        smp = _get(ops, "sample").replace("\\", "/")
        p = os.path.join(base_dir, default_path, smp)
        lvl, dur = cache[p]
        lovel = int(_get(ops, "lovel", "0"))
        hivel = int(_get(ops, "hivel", "127"))
        tgt = target(lovel, hivel)
        vol = tgt - lvl
        for k, v in ops:
            if k in ("volume", "lovel", "hivel", "sample"):
                continue
            out.append(f"{k}={v}")
        out.append(f"sample={smp}")
        out.append(f"volume={vol:.2f}")
        if mode == "sustain":
            h = xfade_width / 2.0
            if lovel > 0:
                out.append(f"xfin_locc1={max(0, int(round(lovel - h)))} xfin_hicc1={min(127, int(round(lovel + h)))}")
            if hivel < 127:
                out.append(f"xfout_locc1={max(0, int(round(hivel + 1 - h)))} xfout_hicc1={min(127, int(round(hivel + 1 + h)))}")
        else:
            out.append(f"lovel={lovel} hivel={hivel}")
        report.append(dict(sample=smp, lokey=_get(ops, "lokey"), hikey=_get(ops, "hikey"),
                           vel=(lovel, hivel), measured_db=round(lvl, 2), volume=round(vol, 2),
                           dur=round(dur, 2)))
    os.makedirs(os.path.dirname(out_sfz), exist_ok=True)
    with open(out_sfz, "w") as f:
        f.write("\n".join(out) + "\n")
    return report


def load_cache(path):
    if os.path.exists(path):
        with open(path) as f:
            return {k: tuple(v) for k, v in json.load(f).items()}
    return {}


def save_cache(path, cache):
    with open(path, "w") as f:
        json.dump(cache, f, indent=0, sort_keys=True)
